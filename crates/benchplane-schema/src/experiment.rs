use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use thiserror::Error;

pub const API_VERSION: &str = "benchplane/v1alpha1";
pub const EXPERIMENT_KIND: &str = "Experiment";
pub const EVIDENCE_FORMAT_V1: &str = "benchplane-evidence/v1";
pub const LOCAL_FAKE_GENERATOR_VERSION: &str = "benchplane-local-fake/v1";
pub const CPU_PROBE_GENERATOR_VERSION: &str = "benchplane-cpu-probe/v1";
pub const CPU_PROBE_WORKLOAD_PROFILE: &str = "cpu-token-probe-v1";
pub const LLAMA_CPP_GENERATOR_VERSION: &str = "benchplane-llama-cpp-smollm2/v1";
pub const LLAMA_CPP_WORKLOAD_PROFILE: &str = "smollm2-chat-greedy-v1";
pub const LLAMA_CPP_MODEL_IDENTITY: &str = "smollm2-135m-instruct-q2-k-v1";
/// Maximum warmup and measured records generated by one local-fake run.
pub const MAX_LOCAL_FAKE_RECORDS: u32 = 10_000;
/// Maximum aggregate measurement records emitted by one CPU-probe child.
pub const MAX_CPU_PROBE_RECORDS: u32 = 1_000;
pub const MAX_CPU_PROBE_OUTPUT_TOKENS: u32 = 4_096;
pub const MAX_CPU_PROBE_WORK_UNITS_PER_TOKEN: u32 = 1_000_000;
pub const MAX_CPU_PROBE_TOTAL_WORK_UNITS: u64 = 100_000_000;
/// Maximum warmup and measured records emitted by the packaged llama.cpp helper.
pub const MAX_LLAMA_CPP_RECORDS: u32 = 16;
pub const MAX_LLAMA_CPP_OUTPUT_TOKENS: u32 = 32;
/// Conservative upper bound for every prompt in the fixed workload profile.
pub const MAX_LLAMA_CPP_PROMPT_TOKENS: u32 = 96;
/// Maximum prompt-plus-generated tokens evaluated across one experiment.
pub const MAX_LLAMA_CPP_TOTAL_TOKENS: u64 = 8_192;

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Experiment {
    pub api_version: String,
    pub kind: String,
    pub metadata: Metadata,
    pub spec: ExperimentSpec,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Metadata {
    pub name: String,
    #[serde(default)]
    pub labels: BTreeMap<String, String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ExperimentSpec {
    pub provider: ProviderSpec,
    pub runtime: RuntimeSpec,
    pub workload: WorkloadSpec,
    #[serde(default)]
    pub measurement: MeasurementSpec,
    pub budget: BudgetSpec,
    #[serde(default)]
    pub lifecycle: LifecycleSpec,
    #[serde(default)]
    pub artifacts: ArtifactSpec,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum ProviderSpec {
    LocalFake,
    Local,
    Aws {
        region: String,
        #[serde(default)]
        capacity: AwsCapacity,
        #[schemars(rename = "instanceTypes")]
        instance_types: Vec<String>,
    },
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, JsonSchema, PartialEq, Eq, Default)]
#[serde(rename_all = "camelCase")]
pub enum AwsCapacity {
    #[default]
    Spot,
    OnDemand,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum RuntimeSpec {
    LocalFake {
        #[serde(default)]
        seed: u64,
        #[serde(default)]
        scenario: LocalFakeScenario,
    },
    CpuProbe {
        #[schemars(range(min = 1, max = 4096))]
        output_tokens: u32,
        #[schemars(range(min = 1, max = 1000000))]
        work_units_per_token: u32,
    },
    LlamaCpp {
        #[serde(default = "default_llama_cpp_model")]
        model: String,
        #[serde(default = "default_llama_cpp_output_tokens")]
        #[schemars(range(min = 1, max = 32))]
        output_tokens: u32,
    },
    Vllm {
        model: String,
        revision: String,
        #[serde(default)]
        arguments: Vec<String>,
    },
}

fn default_llama_cpp_model() -> String {
    LLAMA_CPP_MODEL_IDENTITY.to_owned()
}

fn default_llama_cpp_output_tokens() -> u32 {
    4
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, JsonSchema, PartialEq, Eq, Default)]
#[serde(rename_all = "camelCase")]
pub enum LocalFakeScenario {
    #[default]
    Success,
    RuntimeFailure,
    Interrupted,
    InsufficientMeasurements,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct WorkloadSpec {
    pub profile: String,
    pub requests: u32,
    #[serde(default = "default_concurrency")]
    pub concurrency: u32,
}

fn default_concurrency() -> u32 {
    1
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct MeasurementSpec {
    #[serde(default = "default_warmups")]
    pub warmup_runs: u32,
    #[serde(default = "default_repetitions")]
    pub repetitions: u32,
}

impl Default for MeasurementSpec {
    fn default() -> Self {
        Self {
            warmup_runs: default_warmups(),
            repetitions: default_repetitions(),
        }
    }
}

fn default_warmups() -> u32 {
    1
}

fn default_repetitions() -> u32 {
    3
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct BudgetSpec {
    pub maximum_cost_usd: f64,
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct LifecycleSpec {
    #[serde(default = "default_runtime_seconds")]
    pub maximum_runtime_seconds: u64,
    #[serde(default = "default_true")]
    pub destroy_on_completion: bool,
}

impl Default for LifecycleSpec {
    fn default() -> Self {
        Self {
            maximum_runtime_seconds: default_runtime_seconds(),
            destroy_on_completion: true,
        }
    }
}

fn default_runtime_seconds() -> u64 {
    3600
}

fn default_true() -> bool {
    true
}

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ArtifactSpec {
    #[serde(default)]
    pub public: bool,
    #[serde(default = "default_artifact_format")]
    pub format: String,
}

impl Default for ArtifactSpec {
    fn default() -> Self {
        Self {
            public: false,
            format: default_artifact_format(),
        }
    }
}

fn default_artifact_format() -> String {
    EVIDENCE_FORMAT_V1.to_owned()
}

